# Box drawing: (up, down, left, right), 0 = none, 1 = single, 2 = double
BOX = {
 0xB3:(1,1,0,0), 0xB4:(1,1,1,0), 0xB5:(1,1,2,0), 0xB6:(2,2,1,0), 0xB7:(0,2,1,0), 0xB8:(0,1,2,0),
 0xB9:(2,2,2,0), 0xBA:(2,2,0,0), 0xBB:(0,2,2,0), 0xBC:(2,0,2,0), 0xBD:(2,0,1,0), 0xBE:(1,0,2,0),
 0xBF:(0,1,1,0), 0xC0:(1,0,0,1), 0xC1:(1,0,1,1), 0xC2:(0,1,1,1), 0xC3:(1,1,0,1), 0xC4:(0,0,1,1),
 0xC5:(1,1,1,1), 0xC6:(1,1,0,2), 0xC7:(2,2,0,1), 0xC8:(2,0,0,2), 0xC9:(0,2,0,2), 0xCA:(2,0,2,2),
 0xCB:(0,2,2,2), 0xCC:(2,2,0,2), 0xCD:(0,0,2,2), 0xCE:(2,2,2,2), 0xCF:(1,0,2,2), 0xD0:(2,0,1,1),
 0xD1:(0,1,2,2), 0xD2:(0,2,1,1), 0xD3:(2,0,0,1), 0xD4:(1,0,0,2), 0xD5:(0,1,0,2), 0xD6:(0,2,0,1),
 0xD7:(2,2,1,1), 0xD8:(1,1,2,2), 0xD9:(1,0,1,0), 0xDA:(0,1,0,1),
}
LINES = {1: (3,), 2: (2, 4)}

def box(u, d, l, r):
    g = [[0] * 8 for _ in range(8)]
    def v(x, y0, y1):
        for y in range(y0, y1 + 1): g[y][x] = 1
    def h(y, x0, x1):
        for x in range(x0, x1 + 1): g[y][x] = 1
    tv, th = max(u, d), max(l, r)
    if not (tv and th):                       # straight line
        for c in LINES[tv or th]:
            v(c, 0, 7) if tv else h(c, 0, 7)
        return g
    X, Y = LINES[tv], LINES[th]
    for i, x in enumerate(X):                 # vertical lines: arms + the span between rows
        if u: v(x, 0, Y[0])
        if d: v(x, Y[-1], 7)
        if len(Y) > 1 and (not (l and r) if len(X) == 1 else not (l if i == 0 else r)):
            v(x, Y[0], Y[-1])
    for j, y in enumerate(Y):                 # horizontal lines, likewise
        if l: h(y, 0, X[0])
        if r: h(y, X[-1], 7)
        if len(X) > 1 and (not (u and d) if len(Y) == 1 else not (u if j == 0 else d)):
            h(y, X[0], X[-1])
    return g

for code, arms in BOX.items():
    RAW[code] = ["".join('#' if p else '.' for p in row) for row in box(*arms)]

chr_rom = bytearray(4096)   # 256 tiles; the splash picture fills CHR $1000-$1FFF
for code in range(1, 256):      # tile 0 stays blank in colour 0
    for y in range(8):
        chr_rom[code * 16 + 8 + y] = 0xFF   # plane 1 set: glyph pixels get colour 3

for code, rows in RAW.items():
    for y, b in enumerate(raw(rows)):
        chr_rom[code * 16 + y] = b

# Tile 0xFF: the cursor is a sprite, so it needs a tile whose background is colour 0
# (transparent) rather than the glyph background colour 2.  Only plane 1 is set here,
# so the heart pixels are colour 2 and the surrounding pixels are colour 0.
for y, b in enumerate(raw(RAW[0x03])):
    chr_rom[0xFF * 16 + 8 + y] = b

data = [int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{2})", open(sys.argv[sys.argv.index("--font") + 1]).read())]
assert len(data) == 96 * 8, len(data)
for i in range(0x20, 0x7F):
    for y in range(8):
        chr_rom[i * 16 + y] = data[(i - 0x20) * 8 + y]

open(sys.argv[1], "wb").write(chr_rom)
